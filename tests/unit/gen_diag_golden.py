"""Regenerate tests/unit/diag_golden.h: draws and ArviZ's diagnostics on them.

The C estimators in src/gd_diagnostics.c follow ArviZ line for line; this file
pins that claim to numbers. Run with the ArviZ version named in the header:

    python3 tests/unit/gen_diag_golden.py > tests/unit/diag_golden.h
"""
import numpy as np
import arviz as az
from arviz.stats.diagnostics import _rhat_rank, _ess_bulk, _ess_tail, _ess_mean, _mcse_mean

rng = np.random.default_rng(20261010)
C, N = 4, 101          # odd draw count: the middle draw is dropped on split


def ar1(phi, scale=1.0, shift=None):
    x = np.zeros((C, N))
    for c in range(C):
        e = rng.normal(size=N)
        for i in range(N):
            x[c, i] = (phi * x[c, i - 1] if i else 0.0) + e[i]
    x *= scale
    if shift is not None:
        x += np.asarray(shift)[:, None]
    return x


cases = {
    "iid": rng.normal(size=(C, N)),
    "ar1_09": ar1(0.9),
    "offset_chain": ar1(0.3, shift=[0.0, 0.0, 0.0, 1.5]),
    # Same location, different spread: the bulk R-hat misses it, the folded
    # (tail) R-hat should not.
    "scale_mismatch": rng.normal(size=(C, N)) * np.array([1.0, 1.0, 1.0, 4.0])[:, None],
    "ties": np.round(rng.normal(size=(C, N)) * 2.0),
    # Alternating signs: negative autocorrelation, ESS above the draw count.
    "antithetic": np.tile([(-1.0) ** (i + 1) for i in range(N)], (C, 1)) *
                  rng.uniform(0.5, 1.5, size=(C, N)),
}

print("/* Generated by tests/unit/gen_diag_golden.py with ArviZ %s. Do not edit. */" % az.__version__)
print("#define GOLDEN_C %d" % C)
print("#define GOLDEN_N %d" % N)
print("typedef struct { const char *name; double draws[%d]; double rhat, ess_bulk, ess_tail, ess_mean, mcse_mean; } golden_case;" % (C * N))
print("static const golden_case GOLDEN[] = {")
for name, x in cases.items():
    vals = ", ".join(repr(float(v)) for v in x.ravel())
    stats = [_rhat_rank(x), _ess_bulk(x), _ess_tail(x), _ess_mean(x), _mcse_mean(x)]
    print('  { "%s", { %s },\n    %s },' % (name, vals, ", ".join(repr(float(np.asarray(s).squeeze())) for s in stats)))
print("};")
